package com.study.teller.vo;

public class BizDateVo {

    private String baseDate;
    private String bizYn;
    private String closeYn;
    private String holidayNm;

    public String getBaseDate() { return baseDate; }
    public void setBaseDate(String baseDate) { this.baseDate = baseDate; }

    public String getBizYn() { return bizYn; }
    public void setBizYn(String bizYn) { this.bizYn = bizYn; }

    public String getCloseYn() { return closeYn; }
    public void setCloseYn(String closeYn) { this.closeYn = closeYn; }

    public String getHolidayNm() { return holidayNm; }
    public void setHolidayNm(String holidayNm) { this.holidayNm = holidayNm; }
}